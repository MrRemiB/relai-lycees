import assert from 'node:assert/strict';
import {csvCell,addDays,parisDate,hasCoordinates,schoolFilter,safeURL} from '../static/utils.js';
assert.equal(addDays('2026-10-09',7),'2026-10-16');
assert.equal(addDays('2026-12-25',21),'2027-01-15');
assert.equal(parisDate('2026-10-16T22:00:00Z'),'2026-10-17');
assert.equal(parisDate('2026-11-01T23:00:00Z'),'2026-11-02');
assert.equal(csvCell('=HYPERLINK("https://bad.example")'),'"\'=HYPERLINK(""https://bad.example"")"');
assert.equal(csvCell('  +1'),'"\'  +1"');
assert.equal(csvCell('Texte;"ligne"'),'"Texte;""ligne"""');
assert.equal(safeURL('javascript:alert(1)'),null);
assert.equal(safeURL('https://data.education.gouv.fr/'),'https://data.education.gouv.fr/');
assert.equal(hasCoordinates({lat:null,lon:2}),false);
assert.equal(hasCoordinates({lat:0,lon:0}),true);
const school={id:'0210015C',name:'Lycée Carnot',city:'Dijon',sector:'Public',academy:'Dijon'};
assert.equal(schoolFilter(school,{search:'lycee',sector:'Public'}),true);
assert.equal(schoolFilter(school,{search:'0210015C',sector:'Public'}),true);
assert.equal(schoolFilter(school,{academy:'Réunion',sector:'Public'}),false);
assert.equal(schoolFilter({...school,sector:null},{sector:'Public'}),false);
assert.equal(schoolFilter({...school,sector:null},{sector:''}),true);
console.log('16 frontend utility assertions passed (UTC/Paris, calendar boundary, CSV injection, XSS URL, coordinates, filters).');
